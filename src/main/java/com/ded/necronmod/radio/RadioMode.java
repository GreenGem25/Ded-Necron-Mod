package com.ded.necronmod.radio;

/** Как звучит радио для игрока. */
public enum RadioMode {
    /** Блок в мире: моно, затухание по расстоянию, панорама как у ванильных звуков. */
    POSITIONAL,
    /** Наушники: стерео, прямо в ушах, без затухания и панорамы, где бы ни находился игрок. */
    HEADPHONES
}
